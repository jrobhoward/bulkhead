#!/usr/bin/env bash
# Writes the TLC configs for DrFailover.tla (DrF_*) and DrReplication.tla
# (DrR_*). Run from docs/tla (moved from spikes/s38 with ROADMAP DR4).
set -euo pipefail

# fcfg NAME "SWITCH=VALUE ..." "CHECKS": DrFailover, from docs/tla's
# L2_Crashes_Fixed1 (one fault: a crash, a witness crash or a lost link)
# with an activation and the site cut. CHECKS: INVARIANT and PROPERTY
# lines, separated by ';'.
fcfg() {
    local name=$1 overrides=$2 checks=$3
    declare -A c=(
        [Lease]=4 [Margin]=1 [Timeout]=2 [Delay]=1 [MaxEpoch]=3 [QueueLen]=1 [MaxFaults]=1
        [EchoLease]=TRUE [ConfirmOnSend]=TRUE [PersistEpoch]=TRUE [ForgetRenewals]=TRUE
        [LanFaults]=TRUE [SerialFaults]=TRUE [WanFaults]=TRUE [Crashes]=TRUE
        [WitnessCrashes]=TRUE [Holds]=FALSE [OperatorConfirms]=TRUE [SerialLost]=FALSE
        [MaxSwitchovers]=0 [FastHandover]=FALSE [ReleaseClears]=TRUE
        [Activations]=1 [SiteLease]=TRUE [SiteLeaseLen]=5 [OperatorRight]=FALSE
        [SiteFaults]=TRUE [FenceRefusesAll]=TRUE [WitnessResetsSite]=TRUE
        [DrApart]=FALSE [MaxDwFaults]=0 [HandBacks]=0 [DCrashes]=FALSE [DUnfreezes]=FALSE
        [DTrustsDisk]=FALSE
    )
    local kv
    for kv in $overrides; do c[${kv%%=*}]=${kv#*=}; done
    {
        echo "\\* Generated by dr-mkcfg.sh."
        echo "SPECIFICATION Spec"
        echo
        echo "CONSTANTS"
        echo "    A = A"
        echo "    B = B"
        echo "    W = W"
        echo "    D = D"
        local k
        for k in Lease Margin Timeout Delay MaxEpoch QueueLen MaxFaults EchoLease ConfirmOnSend \
                 PersistEpoch ForgetRenewals LanFaults SerialFaults WanFaults Crashes \
                 WitnessCrashes Holds OperatorConfirms SerialLost MaxSwitchovers FastHandover \
                 ReleaseClears Activations SiteLease SiteLeaseLen OperatorRight SiteFaults \
                 FenceRefusesAll WitnessResetsSite DrApart MaxDwFaults HandBacks DCrashes \
                 DUnfreezes DTrustsDisk; do
            echo "    $k = ${c[$k]}"
        done
        echo
        echo "CONSTRAINT EpochBound"
        echo "$checks" | tr ';' '\n' | sed 's/^ *//'
    } > "$name.cfg"
}

FSAFE="INVARIANT AtMostOneRunningSites;INVARIANT AtMostOneRunning;INVARIANT AtMostOnePrimaryPerEpoch"

# The two remedies, exhaustively: one fault (the site cut among them) and
# an activation at any moment.
fcfg DrF_SiteLease1 "" "$FSAFE"
fcfg DrF_SiteLease_holds1 "Holds=TRUE" "$FSAFE"
fcfg DrF_Operator1 "SiteLease=FALSE OperatorRight=TRUE" "$FSAFE"
# The ROADMAP's proposal as written: no site lease, the witness waits out
# the lease it knows of, the operator activates whatever site 1's state.
# No fault is needed: a pair that hears itself keeps renewing. With the
# site cut as the only fault, the case S38 names.
NOFAULTS="LanFaults=FALSE SerialFaults=FALSE WanFaults=FALSE Crashes=FALSE WitnessCrashes=FALSE OperatorConfirms=FALSE"
fcfg DrF_Proposal "SiteLease=FALSE OperatorRight=FALSE MaxFaults=0 $NOFAULTS" "$FSAFE"
fcfg DrF_Proposal_Cut "SiteLease=FALSE OperatorRight=FALSE $NOFAULTS" "$FSAFE"
# The remedies with the site's own faults only (cut, or both nodes down).
fcfg DrF_SiteLease_Site1 "$NOFAULTS" "$FSAFE"
fcfg DrF_SiteLease_Site_holds1 "Holds=TRUE $NOFAULTS" "$FSAFE"
fcfg DrF_Operator_Site1 "SiteLease=FALSE OperatorRight=TRUE $NOFAULTS" "$FSAFE"
# Rule-off: grants while fencing; a witness restart forgetting its renewals.
fcfg DrF_NoFenceRefusal "FenceRefusesAll=FALSE" "$FSAFE"
fcfg DrF_NoWitnessReset_W "WitnessResetsSite=FALSE LanFaults=FALSE SerialFaults=FALSE WanFaults=FALSE Crashes=FALSE OperatorConfirms=FALSE SiteFaults=FALSE" "$FSAFE"
fcfg DrF_NoWitnessReset "WitnessResetsSite=FALSE" "$FSAFE"
# With no activation and no site lease: FailoverL2's L2_Crashes_Fixed1.
fcfg DrF_Off1 "Activations=0 SiteLease=FALSE SiteFaults=FALSE" "$FSAFE"
# Two faults, by random simulation.
fcfg DrF_SiteLease2 "MaxFaults=2" "$FSAFE"
fcfg DrF_Operator2 "MaxFaults=2 SiteLease=FALSE OperatorRight=TRUE" "$FSAFE"
# ROADMAP DR4b: a DR node apart from the witness, operator fencing. One
# site fault and one D fault (its link to the witness lost, D crashed or
# the witness crashed), an activation and a failback, exhaustively; every
# fault by simulation.
APART="SiteLease=FALSE OperatorRight=TRUE DrApart=TRUE MaxDwFaults=1 HandBacks=1 DCrashes=TRUE"
fcfg DrF_Apart_Site1 "$APART $NOFAULTS WitnessCrashes=TRUE" "$FSAFE"
fcfg DrF_Apart_Site_holds1 "$APART $NOFAULTS WitnessCrashes=TRUE Holds=TRUE" "$FSAFE"
fcfg DrF_Apart1 "$APART" "$FSAFE"
fcfg DrF_Apart2 "$APART MaxFaults=2" "$FSAFE"
# Rule-off: each must find the singleton at two sites, exhaustively with
# only the faults it needs. A frozen D that leads again on a timeout, W's
# answer to its hand-back lost (one D fault, no crash: without a loss the
# answer always reaches D before the pair node's grant, and D stops); a
# restarted D that leads from its own record (D's crash, no witness crash).
fcfg DrF_Apart_Unfreeze "$APART $NOFAULTS DUnfreezes=TRUE DCrashes=FALSE" "$FSAFE"
fcfg DrF_Apart_TrustDisk "$APART $NOFAULTS DTrustsDisk=TRUE" "$FSAFE"
# Vacuity: each must be violated.
fcfg DrF_Vac_ApartRun "$APART $NOFAULTS WitnessCrashes=TRUE" "INVARIANT NoApartRun"
fcfg DrF_Vac_ApartHandBack "$APART $NOFAULTS WitnessCrashes=TRUE" "INVARIANT NoApartHandBack"
fcfg DrF_Vac_Run "" "INVARIANT NoDrRun"
fcfg DrF_Vac_OperatorRun "SiteLease=FALSE OperatorRight=TRUE" "INVARIANT NoDrRun"
fcfg DrF_Vac_SiteFence "" "INVARIANT NoSiteFence"
fcfg DrF_Vac_Leased "" "INVARIANT NoLeasedRunner"

# rcfg NAME FAULTS DOWN "SWITCH=VALUE ..." "CHECKS": DrReplication, from
# S20's Eager1 (the implementation's rules) with the DR replica.
rcfg() {
    local name=$1 faults=$2 down=$3 overrides=$4 checks=$5
    declare -A c=(
        [MaxEpoch]=4 [MaxWrites]=2 [MaxLog]=5 [QueueLen]=1 [MaxSwitchovers]=0
        [Crashes]=TRUE [LanFaults]=TRUE [SerialFaults]=TRUE [WanFaults]=TRUE
        [WitnessCrashes]=TRUE [Compaction]=TRUE
        [Outdated]=TRUE [ReportOnlyInSync]=TRUE [CommitWhileRunning]=TRUE [DurableAck]=TRUE
        [ReadBarrier]=TRUE [LeaseReads]=TRUE [KeepSuffix]=TRUE [PromoteAlone]=FALSE
        [EagerSync]=TRUE [LostAnswers]=FALSE [UnsureRecord]=TRUE
        [Activations]=1 [SiteLease]=TRUE [OperatorRight]=FALSE [SiteFaults]=TRUE [Failback]=TRUE
        [ShipCommittedOnly]=TRUE
    )
    local kv
    for kv in $overrides; do c[${kv%%=*}]=${kv#*=}; done
    {
        echo "\\* Generated by dr-mkcfg.sh."
        echo "SPECIFICATION Spec"
        echo
        echo "CONSTANTS"
        echo "    A = A"
        echo "    B = B"
        echo "    D = D"
        if [ "$faults" = -1 ]; then echo "    MaxFaults <- NoBound"; else echo "    MaxFaults = $faults"; fi
        echo "    MaxDown = $down"
        local k
        for k in MaxEpoch MaxWrites MaxLog QueueLen MaxSwitchovers Crashes LanFaults SerialFaults \
                 WanFaults WitnessCrashes Compaction Outdated ReportOnlyInSync CommitWhileRunning \
                 DurableAck ReadBarrier LeaseReads KeepSuffix PromoteAlone EagerSync LostAnswers \
                 UnsureRecord Activations SiteLease OperatorRight SiteFaults Failback \
                 ShipCommittedOnly; do
            echo "    $k = ${c[$k]}"
        done
        echo
        echo "$checks" | tr ';' '\n' | sed 's/^ *//'
    } > "$name.cfg"
}

RSAFE="INVARIANT TypeOK;INVARIANT RecordKnown;INVARIANT AtMostOneRunningSites;INVARIANT AtMostOneRunning;INVARIANT CommittedAgree;INVARIANT LeaderComplete;INVARIANT ReadLinearizable;INVARIANT DrPrefix;INVARIANT DrNoConflict;INVARIANT StaleInert;INVARIANT DCommittedAgree;PROPERTY NoLostWriteDr;PROPERTY CommittedStable"
RNOFAULTS="Crashes=FALSE LanFaults=FALSE SerialFaults=FALSE WanFaults=FALSE WitnessCrashes=FALSE"

# The two remedies: one fault (a site fault among them), an activation and
# a failback.
rcfg DrR_SiteLease1 1 9 "" "$RSAFE"
rcfg DrR_Operator1 1 9 "SiteLease=FALSE OperatorRight=TRUE" "$RSAFE"
# With the site's own faults only.
rcfg DrR_SiteLease_Site1 1 9 "$RNOFAULTS" "$RSAFE"
rcfg DrR_Operator_Site1 1 9 "SiteLease=FALSE OperatorRight=TRUE $RNOFAULTS" "$RSAFE"
# The proposal as written: no fault needed.
rcfg DrR_Proposal 0 9 "SiteLease=FALSE OperatorRight=FALSE $RNOFAULTS" "$RSAFE"
# Rule-off: D takes entries not yet committed; a crash replaces one.
# Checked against DrNoConflict, not DrPrefix (which fails at once, by
# definition): D then holds an entry a failover replaces.
rcfg DrR_NoCommittedOnly 1 9 "ShipCommittedOnly=FALSE LanFaults=FALSE SerialFaults=FALSE WanFaults=FALSE WitnessCrashes=FALSE SiteFaults=FALSE" "INVARIANT TypeOK;INVARIANT DrNoConflict"
# With no activation: S20's Eager1 (MaxEpoch 3, MaxLog 3, a switchover).
rcfg DrR_Off1 1 9 "Activations=0 SiteLease=FALSE SiteFaults=FALSE Failback=FALSE MaxEpoch=3 MaxLog=3 MaxSwitchovers=1" "$RSAFE"
# Two faults, by random simulation.
rcfg DrR_SiteLease2 2 9 "" "$RSAFE"
rcfg DrR_Operator2 2 9 "SiteLease=FALSE OperatorRight=TRUE" "$RSAFE"
# Vacuity: each must be violated.
rcfg DrR_Vac_Ship 1 9 "$RNOFAULTS" "INVARIANT NoShip"
rcfg DrR_Vac_Loss 1 9 "$RNOFAULTS" "INVARIANT NoLoss"
rcfg DrR_Vac_DrWrite 1 9 "$RNOFAULTS" "INVARIANT NoDrWrite"
rcfg DrR_Vac_Failback 1 9 "$RNOFAULTS" "INVARIANT NoFailback"
rcfg DrR_Vac_OperatorLoss 1 9 "SiteLease=FALSE OperatorRight=TRUE $RNOFAULTS" "INVARIANT NoLoss"
# The proposal on the data path alone: what site 1 commits after the
# activation replaces what clients were told.
rcfg DrR_Proposal_Data 0 9 "SiteLease=FALSE OperatorRight=FALSE $RNOFAULTS" "INVARIANT TypeOK;INVARIANT CommittedAgree;INVARIANT DrPrefix;INVARIANT DCommittedAgree;PROPERTY NoLostWriteDr"
